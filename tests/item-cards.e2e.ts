import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtemp, mkdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import { createApp } from '../server/app.js';
import { SqliteStore } from '../server/store.js';
import { FixtureCards } from './fixtures.js';
import type { ItemCardId } from '../shared/types.js';

const dir=await mkdtemp(path.join(os.tmpdir(),'ygoguess-items-e2e-'));
const store=new SqliteStore(path.join(dir,'items.sqlite'));
const app=await createApp({store,cards:new FixtureCards()});
await new Promise<void>(resolve=>app.server.listen(0,'127.0.0.1',resolve));
const base='http://127.0.0.1:'+(app.server.address() as {port:number}).port;
const browser=await chromium.launch({headless:true,...(process.env.BROWSER_PATH?{executablePath:process.env.BROWSER_PATH}:{})});
try{
  const host=await browser.newPage({viewport:{width:1440,height:1000}});
  const guest=await browser.newPage({viewport:{width:1440,height:1000}});
  await host.goto(base);
  await host.getByLabel('你的昵称').fill('游星');
  await host.getByRole('radio',{name:'随机分配'}).check();
  await host.getByRole('button',{name:'创建房间，邀请朋友'}).click();
  await host.locator('.code-copy').waitFor();
  const code=(await host.locator('.code-copy').innerText()).trim();
  await guest.goto(base+'/?room='+code);
  await guest.getByLabel('你的昵称').fill('海马');
  await guest.getByRole('button',{name:'加入牌桌',exact:true}).click();
  await guest.getByRole('button',{name:'我准备好了'}).click();
  await host.getByRole('button',{name:'开始游戏',exact:true}).click();
  const room=app.hub.rooms.get(code)!;
  assert.equal(room.phase,'guessing');
  const playerId=room.turnPlayerId!;
  const targetId=room.entries.find(entry=>entry.playerId!==playerId)!.playerId;
  const answerIds=room.entries.map(entry=>entry.card?.cid);
  const hand=room.entries.find(entry=>entry.playerId===playerId)!.itemCards!;
  for(const cardId of ['prohibition-card','maxx-c-card','mask-change-card'] as ItemCardId[])hand.push({instanceId:randomUUID(),cardId});
  app.hub.broadcast();
  const item=(name:string)=>host.locator('article.item-card').filter({hasText:name}).first();
  await item('假面卡').waitFor();
  await host.locator('article.item-card img').evaluateAll(async images=>{await Promise.all(images.map(image=>(image as HTMLImageElement).decode()));});
  await mkdir('test-results/item-flow',{recursive:true});
  await host.screenshot({path:'test-results/item-flow/06-redrawn-card-art.png',fullPage:true});
  await item('禁止卡').locator('select').selectOption({label:'海马'});
  await item('禁止卡').getByRole('button',{name:'使用道具卡'}).click();
  await host.getByRole('log').getByText(/使用了禁止卡/).waitFor();
  assert.equal(app.hub.rooms.get(code)!.entries.find(entry=>entry.playerId===targetId)!.skipNextTurns,1);
  await item('增殖卡').getByRole('button',{name:'使用道具卡'}).click();
  await host.locator('.roach-swarm img').first().waitFor();
  assert.equal(await host.locator('.roach-swarm img').count(),16);
  assert(await host.locator('.roach-swarm img').evaluateAll(images=>images.every(image=>parseInt((image as HTMLImageElement).style.width,10)>=28)));
  await host.screenshot({path:'test-results/item-flow/04-roaches.png',fullPage:true});
  await item('假面卡').getByRole('button',{name:'使用道具卡'}).click();
  await host.locator('.mask-appearance-badge').first().waitFor();
  assert.equal(await host.locator('.mask-appearance-badge').count(),2);
  assert.equal(await host.locator('.masked-card').count(),2);
  assert.deepEqual(await host.locator('.masked-card').first().evaluate(element=>[getComputedStyle(element).animationName,getComputedStyle(element,'::after').animationName]),['mask-border-glow','mask-inner-glow']);
  await host.locator('.card-image-button img').evaluateAll(async images=>{await Promise.all(images.map(image=>(image as HTMLImageElement).decode().catch(()=>{})));});
  const imageWidths=await host.locator('.card-image-button img').evaluateAll(images=>images.map(image=>(image as HTMLImageElement).naturalWidth));
  assert.equal(imageWidths.length,2);
  assert(imageWidths.every(width=>width>0));
  await host.screenshot({path:'test-results/item-flow/05-masks.png',fullPage:true});
  assert.equal(new Set(Object.values(app.hub.rooms.get(code)!.visualEffects!.masks!.appearances).map(hero=>hero.id)).size,2);
  assert.deepEqual(app.hub.rooms.get(code)!.entries.map(entry=>entry.card?.cid),answerIds);
  const live=app.hub.rooms.get(code)!;
  live.visualEffects!.roaches!.endsAt=Date.now()-1;
  await host.locator('.roach-swarm img').first().waitFor({state:'detached',timeout:4000});
  await host.screenshot({path:'test-results/item-flow/07-mask-glow.png',fullPage:true});
  app.hub.rooms.get(code)!.visualEffects!.masks!.endsAt=Date.now()-1;
  await host.locator('.mask-appearance-badge').first().waitFor({state:'detached',timeout:4000});
  await host.getByRole('button',{name:'跳过回合',exact:true}).click();
  await host.getByRole('log').getByText('海马 的回合被禁止卡跳过').waitFor();
  const itemMessages=host.locator('.chat-messages .system-message.item-card');
  assert.equal(await itemMessages.count(),4);
  assert.equal(await itemMessages.first().locator('svg').count(),1);
  assert.match(await itemMessages.first().evaluate(element=>getComputedStyle(element).backgroundImage),/linear-gradient/);
  await host.locator('.chat-panel').screenshot({path:'test-results/item-flow/08-item-chat-messages.png'});
  assert.equal(app.hub.rooms.get(code)!.turnPlayerId,playerId);
  assert.equal(app.hub.rooms.get(code)!.entries.find(entry=>entry.playerId===targetId)!.turns,0);
  console.log('PASS item cards browser flow');
}finally{
  await browser.close();
  await app.close();
  await store.close();
}
