import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtemp, mkdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import { createApp } from '../server/app.js';
import { SqliteStore } from '../server/store.js';
import { FixtureCards } from './fixtures.js';
import { finishRound } from '../server/engine.js';
import type { ItemCardId } from '../shared/types.js';

const dir=await mkdtemp(path.join(os.tmpdir(),'ygoguess-new-items-e2e-'));
const store=new SqliteStore(path.join(dir,'items.sqlite'));
const app=await createApp({store,cards:new FixtureCards()});
await new Promise<void>(resolve=>app.server.listen(0,'127.0.0.1',resolve));
const base='http://127.0.0.1:'+(app.server.address() as {port:number}).port;
const browser=await chromium.launch({headless:true,...(process.env.BROWSER_PATH?{executablePath:process.env.BROWSER_PATH}:{})});
try {
  const host=await browser.newPage({viewport:{width:1440,height:1000}});
  const guest=await browser.newPage({viewport:{width:1440,height:1000}});
  await host.goto(base);
  await host.getByLabel('你的昵称').fill('游星');
  await host.getByRole('radio',{name:'随机分配'}).check();
  await host.getByRole('button',{name:'创建房间，邀请朋友'}).click();
  await host.locator('.code-copy').waitFor();
  const code=(await host.locator('.code-copy').innerText()).trim();
  await guest.goto(base+'/?room='+code);
  await guest.getByLabel('你的昵称').fill('海马');
  await guest.getByRole('button',{name:'加入牌桌',exact:true}).click();
  await guest.getByRole('button',{name:'我准备好了'}).click();
  await host.getByRole('button',{name:'开始游戏',exact:true}).click();
  const room=app.hub.rooms.get(code)!;
  assert.equal(room.phase,'guessing');
  assert.equal(room.turnPlayerId,room.hostId);
  const targetId=room.entries.find(entry=>entry.playerId!==room.hostId)!.playerId;
  const hand=room.entries.find(entry=>entry.playerId===room.hostId)!.itemCards!;
  for(const cardId of ['chance-card','lightning-card','fireball-card','outer-entity-card','god-rage-card','crossout-card','scanner-card'] as ItemCardId[])hand.push({instanceId:randomUUID(),cardId});
  app.hub.broadcast();
  const item=(name:string)=>host.locator('article.item-card').filter({hasText:name}).first();
  await item('扫描卡').waitFor();
  await host.locator('article.item-card img').evaluateAll(async images=>{await Promise.all(images.map(image=>(image as HTMLImageElement).decode()));});
  await mkdir('test-results/item-flow',{recursive:true});
  await host.screenshot({path:'test-results/item-flow/09-new-item-art.png',fullPage:true});
  await host.locator('.item-hand-list').evaluate(element=>{element.scrollLeft=element.scrollWidth;});
  await host.screenshot({path:'test-results/item-flow/09b-new-item-art-rest.png',fullPage:true});
  const attempts=room.entries[0].attempts;
  await item('机会卡').getByRole('button',{name:'使用道具卡'}).click();
  await host.locator('[data-testid="player-'+room.hostId+'"] .player-stats').getByText((attempts+1)+' 次机会').waitFor();
  await item('扫描卡').getByRole('button',{name:'使用道具卡'}).click();
  await host.getByRole('log').getByText(/使用了扫描卡：自己的卡名去空格后共有/).waitFor();
  await item('雷击卡').getByRole('button',{name:'使用道具卡'}).click();
  await host.locator('.lightning-storm .lightning-bolt').first().waitFor();
  assert.equal(await host.locator('.lightning-bolt').count(),2);
  await item('火球卡').locator('select').selectOption({label:'海马'});
  await item('火球卡').getByRole('button',{name:'使用道具卡'}).click();
  await host.locator('[data-testid="player-'+targetId+'"] .burning-card').waitFor();
  await item('外神卡').getByRole('button',{name:'使用道具卡'}).click();
  await host.locator('.distorted-card').first().waitFor();
  assert.equal(await host.locator('.distorted-card').count(),2);
  await item('神愤卡').locator('select').selectOption({label:'海马'});
  await item('神愤卡').getByRole('button',{name:'使用道具卡'}).click();
  await host.locator('[data-testid="player-'+targetId+'"] .card-name-cover').waitFor();
  assert.equal(await host.locator('[data-testid="player-'+targetId+'"] .caption-name-cover').count(),1);
  assert.equal(await host.locator('[data-testid="player-'+targetId+'"] .card-image-button').getAttribute('aria-label'),'卡名已被遮挡');
  await item('指名卡').getByRole('button',{name:'使用道具卡'}).click();
  await host.getByRole('log').getByText(/使用了指名卡/).waitFor();
  assert.equal(app.hub.rooms.get(code)!.visualEffects?.obscuredPlayerIds?.[0],targetId);
  await host.screenshot({path:'test-results/item-flow/10-new-item-effects.png',fullPage:true});
  const current=app.hub.rooms.get(code)!;
  current.visualEffects!.lightning!.endsAt=Date.now()-1;
  current.visualEffects!.fireballs![targetId].endsAt=Date.now()-1;
  current.visualEffects!.distortion!.endsAt=Date.now()-1;
  await host.locator('.lightning-storm').waitFor({state:'detached',timeout:4000});
  await host.locator('.burning-card').waitFor({state:'detached',timeout:4000});
  await host.locator('.distorted-card').waitFor({state:'detached',timeout:4000});
  finishRound(app.hub.rooms.get(code)!);
  app.hub.broadcast();
  await host.locator('.card-name-cover').waitFor({state:'detached'});
  await host.getByRole('button',{name:'开始下一局'}).click();
  assert.equal(app.hub.rooms.get(code)!.visualEffects?.obscuredPlayerIds,undefined);
  console.log('PASS new item cards browser flow');
} finally {
  await browser.close();
  await app.close();
  await store.close();
}
