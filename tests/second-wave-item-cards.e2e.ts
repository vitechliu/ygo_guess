import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtemp, mkdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import { createApp } from '../server/app.js';
import { SqliteStore } from '../server/store.js';
import { FixtureCards, cards } from './fixtures.js';
import { guess } from '../server/engine.js';
import type { ItemCardId } from '../shared/types.js';

const dir=await mkdtemp(path.join(os.tmpdir(),'ygoguess-second-wave-e2e-'));
const store=new SqliteStore(path.join(dir,'items.sqlite'));
const app=await createApp({store,cards:new FixtureCards()});
await new Promise<void>(resolve=>app.server.listen(0,'127.0.0.1',resolve));
const base='http://127.0.0.1:'+(app.server.address() as {port:number}).port;
const browser=await chromium.launch({headless:true,...(process.env.BROWSER_PATH?{executablePath:process.env.BROWSER_PATH}:{})});
try {
  const host=await browser.newPage({viewport:{width:1440,height:1000}});
  const guest=await browser.newPage({viewport:{width:1440,height:1000}});
  await host.goto(base);
  await host.getByLabel('你的昵称').fill('游星');
  await host.getByRole('radio',{name:'随机分配'}).check();
  await host.getByRole('button',{name:'创建房间，邀请朋友'}).click();
  await host.locator('.code-copy').waitFor();
  const code=(await host.locator('.code-copy').innerText()).trim();
  await guest.goto(base+'/?room='+code);
  await guest.getByLabel('你的昵称').fill('海马');
  await guest.getByRole('button',{name:'加入牌桌',exact:true}).click();
  await guest.getByRole('button',{name:'我准备好了'}).click();
  await host.getByRole('button',{name:'开始游戏',exact:true}).click();
  const room=app.hub.rooms.get(code)!;
  assert.equal(room.phase,'guessing');
  assert.equal(room.turnPlayerId,room.hostId);
  const hostId=room.hostId;
  const guestId=room.entries.find(entry=>entry.playerId!==hostId)!.playerId;
  const hostHand=room.entries.find(entry=>entry.playerId===hostId)!.itemCards!;
  const guestHand=room.entries.find(entry=>entry.playerId===guestId)!.itemCards!;
  for(const cardId of ['moon-book-card','void-card','reversal-card','puzzle-card','hint-card','stockings-card'] as ItemCardId[])hostHand.push({instanceId:randomUUID(),cardId});
  guestHand.push({instanceId:randomUUID(),cardId:'reborn-card'});
  app.hub.broadcast();
  const item=(page:typeof host,name:string)=>page.locator('article.item-card').filter({hasText:name}).first();
  await item(host,'丝袜卡').waitFor();
  await host.locator('article.item-card img').evaluateAll(async images=>{await Promise.all(images.map(image=>(image as HTMLImageElement).decode()));});
  await mkdir('test-results/item-flow',{recursive:true});
  await host.screenshot({path:'test-results/item-flow/11-second-wave-card-art.png',fullPage:true});
  await host.locator('.item-hand-list').evaluate(element=>{element.scrollLeft=element.scrollWidth;});
  await host.screenshot({path:'test-results/item-flow/11b-second-wave-card-art-rest.png',fullPage:true});
  await item(host,'月书卡').locator('select').selectOption({label:'海马'});
  await item(host,'月书卡').getByRole('button',{name:'使用道具卡'}).click();
  const covered=host.locator('[data-testid="player-'+guestId+'"]');
  await covered.getByAltText('游戏王卡背').waitFor();
  assert.equal(await covered.locator('.caption-name-cover').count(),1);
  assert.equal(await covered.locator('.card-image-button').count(),0);
  assert.equal(await guest.locator('[data-testid="player-'+guestId+'"] img[alt="游戏王卡背"]').count(),1);
  await host.screenshot({path:'test-results/item-flow/12-book-of-moon-face-down.png',fullPage:true});
  await item(host,'虚无卡').getByRole('button',{name:'使用道具卡'}).click();
  await item(host,'谜题卡').getByRole('button',{name:'使用道具卡'}).click();
  await item(host,'提示卡').locator('select').selectOption({label:'海马'});
  await item(host,'提示卡').getByRole('button',{name:'使用道具卡'}).click();
  await item(host,'丝袜卡').getByRole('button',{name:'使用道具卡'}).click();
  for(const text of ['特殊召唤','额外问 1 个问题','请对方给出 1 个提示','多少对丝袜'])await host.getByRole('log').getByText(new RegExp(text)).waitFor();
  await item(host,'逆转卡').getByRole('button',{name:'使用道具卡'}).click();
  await host.locator('.turn-banner').getByText(/逆转卡生效/).waitFor();
  const live=app.hub.rooms.get(code)!;
  const answer=live.entries.find(entry=>entry.playerId===hostId)!.card!;
  guess(live,hostId,cards.find(card=>card.cid!==answer.cid)!,live.turnId);
  app.hub.broadcast();
  assert.equal(live.entries.find(entry=>entry.playerId===hostId)!.status,'failed');
  assert.equal(live.entries.find(entry=>entry.playerId===hostId)!.attempts,0);
  await item(guest,'苏生卡').locator('select').selectOption({label:'游星'});
  await item(guest,'苏生卡').getByRole('button',{name:'使用道具卡'}).click();
  await guest.getByRole('log').getByText(/使用了苏生卡/).waitFor();
  assert.equal(app.hub.rooms.get(code)!.entries.find(entry=>entry.playerId===hostId)!.attempts,1);
  await guest.getByRole('button',{name:'跳过回合',exact:true}).click();
  assert.equal(app.hub.rooms.get(code)!.turnPlayerId,hostId);
  app.hub.rooms.get(code)!.visualEffects!.faceDown![guestId].endsAt=Date.now()-1;
  await covered.getByAltText('游戏王卡背').waitFor({state:'detached',timeout:4000});
  console.log('PASS second-wave item cards browser flow');
} finally {
  await browser.close();
  await app.close();
  await store.close();
}
