import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtemp, mkdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import { createApp } from '../server/app.js';
import { SqliteStore } from '../server/store.js';
import { FixtureCards, cards } from './fixtures.js';
import type { ItemCardId } from '../shared/types.js';

const dir=await mkdtemp(path.join(os.tmpdir(),'ygo-arrow-'));
const store=new SqliteStore(path.join(dir,'test.sqlite'));
const localCards=cards.map((card,i)=>({...card,name:i%2?'黑魔术师':'青眼白龙',image:i%2?'/debug-dark-magician-card.webp':'/debug-blue-eyes-card.webp'}));
const app=await createApp({store,cards:new FixtureCards(localCards)});
await new Promise<void>(resolve=>app.server.listen(0,'127.0.0.1',resolve));
const base='http://127.0.0.1:'+(app.server.address() as {port:number}).port;
const browser=await chromium.launch({headless:true,...(process.env.BROWSER_PATH?{executablePath:process.env.BROWSER_PATH}:{})});
const output='test-results/moon-arrow';
try{
  const host=await browser.newPage({viewport:{width:1440,height:1100}});
  const guest=await browser.newPage({viewport:{width:1440,height:1100}});
  await host.goto(base);await host.getByLabel('你的昵称').fill('游星');
  await host.getByRole('radio',{name:'随机分配'}).check();
  await host.getByRole('button',{name:'创建房间，邀请朋友'}).click();
  await host.locator('.code-copy').waitFor();
  const code=(await host.locator('.code-copy').innerText()).trim();
  await guest.goto(base+'/?room='+code);await guest.getByLabel('你的昵称').fill('海马');
  await guest.getByRole('button',{name:'加入牌桌',exact:true}).click();
  await guest.getByRole('button',{name:'我准备好了'}).click();
  await host.getByRole('button',{name:'开始游戏',exact:true}).click();
  await host.locator('.item-hand').waitFor();
  const room=app.hub.rooms.get(code)!;
  const targetId=room.entries.find(e=>e.playerId!==room.hostId)!.playerId;
  const hand=room.entries.find(e=>e.playerId===room.hostId)!.itemCards!;
  const grant=(cardId:ItemCardId)=>hand.push({instanceId:randomUUID(),cardId});
  for(const id of ['greed-card','warwolf-card','moon-arrow-card'] as const)grant(id);
  app.hub.broadcast();
  const item=(name:string)=>host.locator('article.item-card').filter({hasText:name}).first();
  await item('狼人卡').locator('.item-passive-status').waitFor();
  assert.equal(await item('狼人卡').getByRole('button').count(),0);
  assert.equal(await guest.locator('article.item-card').count(),0);
  await host.locator('.item-card img').evaluateAll(async images=>{await Promise.all(images.map(img=>(img as HTMLImageElement).decode()));});
  await mkdir(output,{recursive:true});
  await host.screenshot({path:output+'/new-cards.png',fullPage:true});
  const before=hand.length;
  await item('强欲卡').getByRole('button',{name:'使用道具卡'}).click();
  await host.getByRole('log').getByText(/使用了强欲卡/).waitFor();
  assert.equal(app.hub.rooms.get(code)!.entries.find(e=>e.playerId===room.hostId)!.itemCards!.length,before+1);
  const stats=room.entries.map(e=>({attempts:e.attempts,card:e.card,points:e.points}));
  await item('神弓卡').locator('select').selectOption(targetId);
  await item('神弓卡').getByRole('button',{name:'使用道具卡'}).click();
  const arrow=host.locator('.moon-arrow-weapon');await arrow.waitFor();
  await guest.locator('.moon-arrow-weapon').waitFor();
  assert.equal(await host.locator('.moon-arrow-strike').count(),1);
  await arrow.evaluate(async img=>{await (img as HTMLImageElement).decode();});
  const seek=async(ms:number)=>host.locator('.moon-arrow-impact-card').evaluate((el,time)=>{for(const animation of el.parentElement!.getAnimations({subtree:true})){animation.pause();animation.currentTime=time;}},ms);
  await seek(1495);
  const first=await host.locator('.moon-arrow-impact-card').evaluate(el=>getComputedStyle(el).transform);
  await seek(1625);
  const second=await host.locator('.moon-arrow-impact-card').evaluate(el=>getComputedStyle(el).transform);
  assert.notEqual(first,second,'impact must visibly shake the target card');
  await seek(1750);await host.screenshot({path:output+'/impact.png',fullPage:true});
  await seek(2600);await host.screenshot({path:output+'/pierced.png',fullPage:true});
  const target=host.locator('[data-testid="player-'+targetId+'"]');
  await target.screenshot({path:output+'/pierced-detail.png'});
  assert.deepEqual(app.hub.rooms.get(code)!.entries.map(e=>({attempts:e.attempts,card:e.card,points:e.points})),stats);
  assert.equal(await host.locator('[data-testid="player-'+room.hostId+'"] .card-image-button').count(),0);
  await host.setViewportSize({width:390,height:844});
  await seek(2600);await host.screenshot({path:output+'/mobile.png',fullPage:true});
  assert.equal(await host.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await host.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await host.locator('.moon-arrow-impact-card').evaluate(el=>getComputedStyle(el).animationName),'none');
  app.hub.rooms.get(code)!.visualEffects!.moonArrows![targetId].endsAt=Date.now()-1;
  await arrow.waitFor({state:'detached',timeout:4000});
  assert.equal(app.hub.rooms.get(code)!.visualEffects?.moonArrows,undefined);
  assert.equal((await store.loadRooms()).find(r=>r.code===code)!.visualEffects?.moonArrows,undefined);
  console.log('PASS: private draw, passive UI, multiplayer arrow, shake, expiry, mobile and reduced motion');
}finally{await browser.close();await app.close();await store.close();}
